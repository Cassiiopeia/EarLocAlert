/// 장소별 지오펜스 상태 (docs/03-DOMAIN.md)
///
/// `unknown` 이 핵심이다 — 이게 없으면 앱을 켠 순간 이미 반경 안에 있어도
/// "방금 진입했다"로 오판해 알림이 터진다. 알림은 `outside → inside`
/// 전이에서만 나간다. 밖에 있었다는 사실이 확인된 적이 있어야
/// 진입 알림이 의미를 갖는다.
enum GeofenceState {
  /// 아직 판정된 적 없음 (등록 직후, 신호 장기 두절 후)
  unknown,

  /// 반경 안
  inside,

  /// 반경 밖
  outside,
}
