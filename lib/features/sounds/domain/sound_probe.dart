/// 음원 파일이 실제로 재생 가능한지 확인한다 (이슈 #121)
///
/// **확장자만 믿지 않기 위해 존재한다.** `.mp3` 로 이름만 바꾼 파일,
/// 손상된 파일, 코덱이 지원되지 않는 파일은 여기서 걸러진다 — 걸러내지
/// 않으면 알림이 울려야 할 순간에 재생이 실패해 진동만 남는다.
abstract interface class SoundProbe {
  /// 재생 가능하면 길이를, 아니면 `null` 을 돌려준다.
  ///
  /// **예외를 던지지 않는다.** 디코딩 실패는 정상적인 결과 중 하나다.
  Future<Duration?> probe(String filePath);
}
